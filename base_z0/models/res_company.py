from odoo import models
from odoo.addons.base.res.res_company import Company

ODOO_FOOTER = "generated by Odoo.com"
Z0_FOOTER = "generated by Zeroincombenze(R)"


class ResCompany(models.Model):
    _inherit = "res.company"

    # Default RML headers used by new companies and by the paper format change
    _header_main = Company._header_main.replace(ODOO_FOOTER, Z0_FOOTER)
    _header_a4 = Company._header_a4.replace(ODOO_FOOTER, Z0_FOOTER)
    _header_letter = Company._header_letter.replace(ODOO_FOOTER, Z0_FOOTER)
